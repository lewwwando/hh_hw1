-- Исправленный запрос:
SELECT
	v.professional_role,
	count(DISTINCT v.vacancy_id ) AS vacancies,
	round(
1.0 * count(r.response_id) / 
NULLIF(count(DISTINCT v.vacancy_id), 0),
1) AS responses_per_vacancy
FROM
	vacancies v
LEFT JOIN responses r ON
	v.vacancy_id = r.vacancy_id
WHERE
	v.closed_at IS NULL
GROUP BY
	1;

